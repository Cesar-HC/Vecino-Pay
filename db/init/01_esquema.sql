-- Tabla 33: la auditoría solo admite inserciones (falla aunque la sentencia no toque filas, como el original).
CREATE OR REPLACE FUNCTION fn_auditoria_solo_insercion() RETURNS trigger
LANGUAGE plpgsql SET search_path = public AS $fn$
BEGIN
  RAISE EXCEPTION 'La auditoría solo admite inserciones.' USING ERRCODE = 'VP001';
END;
$fn$;

CREATE OR REPLACE TRIGGER tr_auditoria_solo_insercion
BEFORE UPDATE OR DELETE OR TRUNCATE ON auditoria
FOR EACH STATEMENT EXECUTE FUNCTION fn_auditoria_solo_insercion();

-- Aislamiento multitienda sin columnas nuevas (las Tablas 28 y 31 no tienen tienda_id).
CREATE OR REPLACE FUNCTION fn_compra_detalle_misma_tienda() RETURNS trigger
LANGUAGE plpgsql SET search_path = public AS $fn$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM compra c, producto p
    WHERE c.id = NEW.compra_id AND p.id = NEW.producto_id AND p.tienda_id <> c.tienda_id
  ) THEN
    RAISE EXCEPTION 'El producto debe pertenecer a la misma tienda que la compra.' USING ERRCODE = 'VP002';
  END IF;
  RETURN NULL;
END;
$fn$;

CREATE OR REPLACE TRIGGER tr_compra_detalle_misma_tienda
AFTER INSERT OR UPDATE ON compra_detalle
FOR EACH ROW EXECUTE FUNCTION fn_compra_detalle_misma_tienda();

CREATE OR REPLACE FUNCTION fn_listado_item_mismo_cliente() RETURNS trigger
LANGUAGE plpgsql SET search_path = public AS $fn$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM listado_pago l
    LEFT JOIN cuota q ON q.id = NEW.cuota_id
    JOIN compra c ON c.id = COALESCE(NEW.compra_id, q.compra_id)
    WHERE l.id = NEW.listado_id
      AND (c.cliente_id <> l.cliente_id
        OR (NEW.tipo = 'COMPRA' AND c.modalidad <> 'FIN_MES')
        OR (NEW.tipo = 'CUOTA' AND c.modalidad <> 'CUOTAS'))
  ) THEN
    RAISE EXCEPTION 'El ítem debe ser del mismo cliente del listado y coincidir con la modalidad de la compra.' USING ERRCODE = 'VP003';
  END IF;
  RETURN NULL;
END;
$fn$;

CREATE OR REPLACE TRIGGER tr_listado_item_mismo_cliente
AFTER INSERT OR UPDATE ON listado_item
FOR EACH ROW EXECUTE FUNCTION fn_listado_item_mismo_cliente();

